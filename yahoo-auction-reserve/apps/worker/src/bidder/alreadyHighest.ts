// ページの「あなたが最高額入札者です」を信用してよいかの判定。
//
// なぜ要るか(2026-09-19 の実害 l1244376785):
// 入札成功 → ヤフオクの自動延長 → 5分後の再スナイプ、という流れで placeBid が
// 5分前の DOM を読み、他人に高値更新されているのに「すでに最高額入札者」と
// 判断して **一度も入札しないまま LOST** になった。
// 根本原因は placeBid 側で直してある(入札フローに触れたページは再利用しない)。
// ここはその上に重ねる2層目。
//
// なぜ2層にするか: この判定は「黙って落札機会を失う」形で壊れる。
// 入札しなかったことは通知にも「入札せず」としか出ないので、予約が空振りした
// ことに誰も気づけない。ページの読み方を1か所直しただけで安心してよい種類の
// 故障ではない。
//
// ── 打ち消す根拠 ──────────────────────────────────────────────
// ヤフオクは上限額方式(代理入札)なので、自分が最高額入札者でいる限り
// 現在価格が **自分の入れた上限額を超えることはない**
// (対抗者が来ても自分の上限まで自動で競り上がるだけ)。つまり
//
//     新鮮な現在価格 > 前回自分が入れた額  ⇒  自分は最高額入札者ではありえない
//
// が成り立つ。現在価格は fetchAuctionInfo という **ページとは別経路** の取得
// なので、ページが古いときでもこちらは新鮮でいられる。実際 2026-09-19 の
// ログでは「現在 ¥29000 / 前回入札 ¥22500」と、この不等式が成立していた。
//
// ⚠️ currentPrice が古くても安全側に倒れる。monitor は「価格確認 → スナイプ時刻
// まで待機 → 入札」の順なので、この価格は入札の瞬間より前のものでありうる。
// ただしオークションの価格は上がる一方なので、古い価格が上限を超えていたなら
// 今の価格も必ず超えている。**取りこぼす方向にしかずれない**(打ち消すべき場面で
// 打ち消し損ねることはあっても、打ち消してはいけない場面で打ち消すことはない)。
// だからここで取り直さない。取り直すと入札直前に1往復増える。
//
// ⚠️ 打ち消すのは「ありえない」と確証があるときだけ。材料が無いとき
// (まだ入札していない / 価格が取れない / 同額)は無効化せず、ページ側の
// ガードにそのまま委ねる。「迷ったら打ち消す」にすると、本当に最高額を
// 保っている場面で自分の上限を無意味に上げて回ることになる。

export interface AlreadyHighestGuard {
  /** ページの「最高額入札者」表示による入札中止を有効にしてよいか */
  enabled: boolean;
  /** enabled=false にした理由。⚠️ ログにそのまま出す(黙って無効化しない) */
  reason: string;
}

export function alreadyHighestGuard(args: {
  /** この監視ジョブで直近に **入札が成立した** 額。未入札なら null */
  lastBidAmount: number | null;
  /** 直前に別経路(fetchAuctionInfo)で取れた現在価格。取れなければ null */
  currentPrice: number | null;
}): AlreadyHighestGuard {
  const { lastBidAmount, currentPrice } = args;
  // まだ一度も入札していない = そもそも最高額入札者になりようがないが、
  // 手動で入札済みの商品を予約した場合はありうる。比較材料が無いので委ねる。
  if (lastBidAmount === null) return { enabled: true, reason: "" };
  // 価格が取れていない回。上限チェック自体も行えていないので、ここも委ねる。
  if (currentPrice === null) return { enabled: true, reason: "" };
  // ⚠️ 同額(===)では打ち消さない。ヤフオクは同額なら先の入札者が上位なので、
  // 自分が最高額のままである可能性が残る。超えたときだけが確証。
  if (currentPrice > lastBidAmount) {
    return {
      enabled: false,
      reason:
        `現在価格 ¥${currentPrice} が前回の入札額 ¥${lastBidAmount} を超えている` +
        `(上限額方式では自分が最高額のまま上限を超えることはない)ため、` +
        `商品ページの「あなたが最高額入札者です」は古い表示として無視します`,
    };
  }
  return { enabled: true, reason: "" };
}
